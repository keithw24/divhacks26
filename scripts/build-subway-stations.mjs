#!/usr/bin/env node
// Builds src/alerts/subwayStations.ts from MTA's station list on data.ny.gov (no key needed).
// Shape: { gtfsStopId: [name, latitude, longitude, "A C E"] }. Rerun when MTA adds or renames stations.
import { writeFileSync } from "node:fs";

const url = "https://data.ny.gov/resource/39hk-dx4f.json?$limit=1000";
const rows = await (await fetch(url)).json();
const stations = {};
for (const row of rows) {
  const lat = Number(row.gtfs_latitude);
  const lon = Number(row.gtfs_longitude);
  if (!row.gtfs_stop_id || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  stations[row.gtfs_stop_id] = [row.stop_name, lat, lon, String(row.daytime_routes ?? "").trim()];
}
const sorted = Object.fromEntries(Object.entries(stations).sort(([a], [b]) => a.localeCompare(b)));
const out = new URL("../src/alerts/subwayStations.ts", import.meta.url);
const body = Object.entries(sorted)
  .map(([id, row]) => `  ${JSON.stringify(id)}: ${JSON.stringify(row)},`)
  .join("\n");
writeFileSync(
  out,
  `// Generated by scripts/build-subway-stations.mjs from MTA's station list (data.ny.gov 39hk-dx4f). Do not edit.
export type StationRow = [name: string, latitude: number, longitude: number, routes: string];

export const SUBWAY_STATIONS: Record<string, StationRow> = {
${body}
};
`,
);
console.log(`wrote ${Object.keys(sorted).length} stations`);
